def test_distance_metrics_helpers():
    """Verify Levenshtein distance calculations handle edge cases safely."""
    assert compute_cer("", "") == 0.0
    assert compute_cer("ABC", "ABC") == 0.0
    assert compute_cer("ABC", "ABD") == pytest.approx(1/3, 0.01)
    assert compute_wer("", "") == 0.0
    assert compute_wer("hello world", "hello world") == 0.0
    assert compute_wer("hello world", "hello there") == pytest.approx(0.5, 0.01)
